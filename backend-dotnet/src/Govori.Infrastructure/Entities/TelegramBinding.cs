using System;

namespace Govori.Infrastructure.Entities;

/// <summary>
/// A Telegram account that has PROVEN, via a contact share where
/// <c>contact.user_id == message.from.id</c>, that it owns <see cref="Phone"/>.
///
/// <para>Additive table (<c>telegram_bindings</c>) — no existing table is touched. The row is a
/// speed cache for the OTP delivery flow: it lets an already-proven pair skip re-proving. It is
/// never, on its own, an authorization decision, and ONLY the Telegram bot poller writes it (see
/// <c>Govori.Platform.Telegram.ITelegramBindingStore</c>).</para>
///
/// <para>Deliberately NOT related to <c>users</c>: a person may prove ownership of a phone that has
/// no account yet (that is exactly the register flow), so a foreign key would reject the first-ever
/// login. <see cref="Phone"/> is the canonical <c>+998XXXXXXXXX</c> form produced by
/// <c>PhoneNumbers.NormalizeUz</c>, matching <c>users.phone</c> in both type and width.</para>
/// </summary>
public partial class TelegramBinding
{
    /// <summary>Telegram's own numeric user id (<c>message.from.id</c>) — the primary key. Supplied
    /// by Telegram, never generated by us.</summary>
    public long TelegramUserId { get; set; }

    /// <summary>Canonical <c>+998XXXXXXXXX</c>. Indexed so a phone can be looked up directly.</summary>
    public string Phone { get; set; } = null!;

    /// <summary>When the proof happened (UTC). Refreshed on every re-proof.</summary>
    public DateTime VerifiedAt { get; set; }
}
